package com.example.chaostarget;

/** An application class with a {@code get()}, the counterpart of {@code HashMap.get}. */
public final class UserMap {

  /** Creates a map. */
  public UserMap() {}

  /**
   * Returns a constant.
   *
   * @return {@code "user"}
   */
  public String get() {
    return "user";
  }
}
